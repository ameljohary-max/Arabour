// الأسعار الأساسية بالجنيه الاسترليني (GBP) — العملة الافتراضية
// USD = GBP × 1.3   |   EUR = GBP × 1.2
const currencyInfo = {
    gbp: { symbol: '£', rate: 1 },
    usd: { symbol: '$', rate: 1.3 },
    eur: { symbol: '€', rate: 1.2 }
};

const planPricesGBP = {
    p1: { old: 100, new: 69, hourly: 11.5 },
    p2: { old: 120, new: 80, hourly: 10 },
    p3: { old: 180, new: 138, hourly: 11.5 }
};

function formatPrice(value, symbol) {
    let v = Math.round(value * 10) / 10;
    v = (v % 1 === 0) ? v.toFixed(0) : v.toFixed(1);
    return symbol + v;
}

function getCurrentCurrency() {
    const saved = localStorage.getItem('selectedCurrency');
    return currencyInfo[saved] ? saved : 'gbp';
}

function updatePricingCurrency(currency) {
    if (!currencyInfo[currency]) currency = 'gbp';
    const lang = localStorage.getItem('selectedLang') || 'en';
    const t = translations[lang] || translations.en;
    const info = currencyInfo[currency];

    ['p1', 'p2', 'p3'].forEach(p => {
        const base = planPricesGBP[p];

        const oldEl = document.getElementById(p + 'Old');
        if (oldEl) oldEl.textContent = formatPrice(base.old * info.rate, info.symbol);

        const newEl = document.getElementById(p + 'NewPrice');
        if (newEl) newEl.textContent = formatPrice(base.new * info.rate, info.symbol);

        const hourlyEl = document.getElementById(p + 'Hourly');
        const tpl = t[p + 'HourlyTpl'] || (translations.en[p + 'HourlyTpl']);
        if (hourlyEl && tpl) {
            hourlyEl.textContent = tpl.replace('{P}', formatPrice(base.hourly * info.rate, info.symbol));
        }
    });

    document.querySelectorAll('.currency-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.currency === currency);
    });

    localStorage.setItem('selectedCurrency', currency);
}

function setCurrency(currency) {
    updatePricingCurrency(currency);
}

