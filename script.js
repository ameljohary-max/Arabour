function setLanguage(lang) {
    localStorage.setItem('selectedLang', lang);

    // تحديث رابط المتصفح فوراً دون تحمبل الصفحة لتضمين رمز اللغة (?lang=ar)
    if (window.history.pushState) {
        const newUrl = window.location.protocol + "//" + window.location.host + window.location.pathname + '?lang=' + lang;
        window.history.pushState({ path: newUrl }, '', newUrl);
    }

    if (lang === 'ar') {
        document.documentElement.dir = 'rtl';
        document.documentElement.lang = 'ar';
        document.body.className = 'lang-ar';
    } else {
        document.documentElement.dir = 'ltr';
        document.documentElement.lang = lang;
        document.body.className = '';
    }

    if (translations[lang]) {
        Object.keys(translations[lang]).forEach(key => {
            if (key === 'studentLevelPlaceholder') {
                const element = document.getElementById('studentLevel');
                if (element) element.placeholder = translations[lang][key];
            } else if (key === 'parentWaPlaceholder') {
                const element = document.getElementById('parentWhatsapp');
                if (element) element.placeholder = translations[lang][key];
            } else if (key === 'countryPlaceholder') {
                const element = document.getElementById('countryName');
                if (element) element.placeholder = translations[lang][key];
            } else if (key === 'statePlaceholder') {
                const element = document.getElementById('stateName');
                if (element) element.placeholder = translations[lang][key];
            } else {
                const element = document.getElementById(key);
                if (element) {
                    element.innerHTML = translations[lang][key];
                }
            }
        });
    }

    // إعادة رسم الأسعار بالعملة الحالية بعد تغيير اللغة (عشان الأسعار متترجمش خطأ)
    updatePricingCurrency(getCurrentCurrency());
}

