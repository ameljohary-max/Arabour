document.querySelectorAll('nav a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();

        const targetId = this.getAttribute('href');
        const targetSection = document.querySelector(targetId);

        if (targetSection) {
            const header = document.querySelector('header');
            if (header) header.classList.add('shrinked');

            const headerHeight = 65;
            const viewportHeight = window.innerHeight;
            const availableSpace = viewportHeight - headerHeight;
            const contentHeight = targetSection.offsetHeight;

            const rawTop = targetSection.getBoundingClientRect().top + window.pageYOffset - headerHeight;

            let targetPosition;
            if (targetId === '#home' || contentHeight > availableSpace) {
                // الهيرو أو أي سكشن أطول من الشاشة: نثبته من فوق زي ما هو
                targetPosition = rawTop;
            } else {
                // السكشن بيتوسط في المساحة الفاضية تحت الهيدر (الفرق بيتقسم فوق وتحت بالتساوي)
                const extraSpace = availableSpace - contentHeight;
                targetPosition = rawTop - (extraSpace / 2);
            }

            window.scrollTo({
                top: Math.max(targetPosition, 0),
                behavior: 'smooth'
            });
        }
    });
});

