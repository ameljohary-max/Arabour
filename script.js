function sendToWhatsApp(event) {
    event.preventDefault();

    const lang = localStorage.getItem('selectedLang') || 'en';
    const t = translations[lang] || translations.en;

    const studentName = document.getElementById('studentName').value.trim();
    const studentLevel = document.getElementById('studentLevel').value.trim();
    const parentName = document.getElementById('parentName').value.trim();
    const parentWhatsapp = document.getElementById('parentWhatsapp').value.trim();
    const parentEmail = document.getElementById('parentEmail').value.trim();
    const countryName = document.getElementById('countryName').value.trim();
    const stateName = document.getElementById('stateName').value.trim();
    const selectedPlan = document.getElementById('selectedPlan').value.trim();
    const selectedPlanPrice = document.getElementById('selectedPlanPrice').value.trim();
    const currency = getCurrentCurrency();
    const currencyLabels = { gbp: 'GBP (£)', usd: 'USD ($)', eur: 'EUR (€)' };

    let selectedCourses = [];
    if (document.getElementById('c1') && document.getElementById('c1').checked) selectedCourses.push(t.lblC1);
    if (document.getElementById('c2') && document.getElementById('c2').checked) selectedCourses.push(t.lblC2);
    if (document.getElementById('c3') && document.getElementById('c3').checked) selectedCourses.push(t.lblC3);

    if (!studentName || !parentName || !parentWhatsapp || selectedCourses.length === 0) {
        alert("Please fill in all required fields and select at least one course.\nيرجى ملء جميع الحقول الإلزامية واختيار مادة واحدة على الأقل.");
        return;
    }

    let location = '';
    if (countryName) location += countryName;
    if (countryName && stateName) location += ' - ';
    if (stateName) location += stateName;

    let message = `      *${t.msgTitle}*\n`;
    message += `\n\n`;

    if (selectedPlan) {
        const planLabel = selectedPlanPrice ? `${selectedPlan} (${selectedPlanPrice})` : selectedPlan;
        message += `• *${t.msgPlan}:* ${planLabel}\n\n`;
    }

    message += `• *${t.msgCurrency}:* ${currencyLabels[currency] || currency}\n\n`;
    message += `• *${t.msgName}:* ${studentName}\n\n`;
    message += `• *${t.msgCourses}:* ${selectedCourses.join(', ')}\n\n`;

    if (studentLevel) {
        message += `• *${t.msgLevel}:* ${studentLevel}\n\n`;
    }

    if (location) {
        message += `• *${t.msgCountry} / ${t.msgState}:* ${location}\n\n`;
    }

    message += `\n\n`;
    message += `• *${t.msgParentName}:* ${parentName}\n\n`;
    message += `• *${t.msgParentWa}:* ${parentWhatsapp}\n\n`;

    if (parentEmail) {
        message += `• *${t.msgParentEmail}:* ${parentEmail}`;
    }

    const academyNumber = "201070487205";
    const whatsappUrl = `https://api.whatsapp.com/send?phone=${academyNumber}&text=${encodeURIComponent(message)}`;

    window.open(whatsappUrl, '_blank');

    closeBooking();
    clearForm();
}

